const dictionaries: Record<LumoraLanguage, ScanDictionary> = {
  en,
  te,
  hi,
  ur,
}

export function scanT(
  language: LumoraLanguage,
  key: ScanKey,
  values: Record<string, string | number> = {},
): string {
  return dictionaries[language][key].replace(
    /\{(\w+)\}/g,
    (_, name: string) => String(values[name] ?? `{${name}}`),
  )
}
